"""Write requirements.lock with every published sha256 for each exact pin.

Usage: python tools/lock_requirements.py packaging/requirements.in requirements.lock

Reads each pinned release's file digests from the PyPI JSON API, so the
lock covers every platform wheel and the sdist of that release. Install
with ``pip install --require-hashes --only-binary :all: -r requirements.lock``.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

PIN = re.compile(r"^(?P<name>[A-Za-z0-9._-]+)==(?P<version>[A-Za-z0-9.+!-]+)\s*(?P<marker>;.*)?$")


def release_digests(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        files = json.load(response)["urls"]
    digests = sorted({f["digests"]["sha256"] for f in files if not f.get("yanked")})
    if not digests:
        raise SystemExit(f"{name}=={version}: no published files")
    return digests


def lock(requirements_in: Path) -> str:
    lines = [
        "# Generated by tools/lock_requirements.py from packaging/requirements.in.",
        "# Do not edit by hand.",
    ]
    for raw in requirements_in.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.match(line)
        if not match:
            raise SystemExit(f"not an exact pin: {line}")
        marker = f" {match['marker'].strip()}" if match["marker"] else ""
        hashes = release_digests(match["name"], match["version"])
        lines.append(f"{match['name']}=={match['version']}{marker} \\")
        continuation = [" \\"] * (len(hashes) - 1) + [""]
        lines.extend(f"    --hash=sha256:{h}{c}" for h, c in zip(hashes, continuation))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    source, target = (Path(a) for a in argv)
    target.write_text(lock(source), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
